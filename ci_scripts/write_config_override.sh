#!/bin/sh
# Writes ConfigOverride.xcconfig at the repo root for an Xcode Cloud build.
# Called by ci_post_clone.sh and ci_pre_xcodebuild.sh. Safe to run more than once.
#
# ConfigOverride.xcconfig is gitignored and is #included by Config.xcconfig, so the
# signing team and CI flags reach the build without editing any tracked file.
set -eu

REPO="${CI_PRIMARY_REPOSITORY_PATH:-$(cd "$(dirname "$0")/.." && pwd)}"

# Xcode Cloud provides CI_TEAM_ID. A TEAM_ID workflow variable overrides it.
TEAM="${TEAM_ID:-${CI_TEAM_ID:-}}"
if [ -z "$TEAM" ]; then
    echo "error: no team ID. Expected CI_TEAM_ID from Xcode Cloud, or a TEAM_ID workflow variable." >&2
    exit 1
fi

OUT="$REPO/ConfigOverride.xcconfig"
{
    echo "// Generated by ci_scripts/write_config_override.sh for Xcode Cloud. Do not commit."
    echo "DEVELOPER_TEAM = $TEAM"
    echo ""
    echo "// Xcode Cloud sets CI=TRUE, but Trio's SwiftFormat and Crashlytics build phases"
    echo "// test for lowercase \"true\" (what GitHub Actions sets). Build settings are exported"
    echo "// to run-script phases, so this makes those phases skip, as they do in the browser build."
    echo "CI = true"
    if [ "${DEV_BRANCH_WARNING_DISABLED:-}" = "true" ]; then
        echo ""
        echo "// Same as the browser build's DEV_BRANCH_WARNING_DISABLED repository variable."
        echo "SWIFT_ACTIVE_COMPILATION_CONDITIONS = \$(inherited) DEV_BRANCH_WARNING_DISABLED"
    fi
} > "$OUT"

echo "Wrote $OUT:"
sed 's/^/    /' "$OUT"
